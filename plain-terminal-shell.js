// How a plain terminal defines its `claude` shim per shell: see .ai/contexts/plain-terminal.md
'use strict';

const fs = require('fs');
const path = require('path');
const { isWslShell } = require('./shell-profiles');

const HINT = 'To start a Claude session, use the + button in the sidebar.';

const POSIX_SHIM = `claude() { printf '\\033[33m%s\\033[0m\\n' '${HINT}'; return 1; }`;

const TYPED_SHIM = ` ${POSIX_SHIM}; export -f claude 2>/dev/null; clear\n`;

const FISH_SHIM = `function claude; set_color yellow; echo '${HINT}'; set_color normal; return 1; end`;

const HEADER = '# Generated by Switchboard for its plain terminals; rewritten at each launch.\n';

const BASHRC = `${HEADER}if [ -f /etc/profile ]; then . /etc/profile; fi
if [ -f "$HOME/.bash_profile" ]; then . "$HOME/.bash_profile"
elif [ -f "$HOME/.bash_login" ]; then . "$HOME/.bash_login"
elif [ -f "$HOME/.profile" ]; then . "$HOME/.profile"
fi
${POSIX_SHIM}
export -f claude 2>/dev/null
`;

const ZSH_USER = 'if [[ -n $_sb_zdotdir_set ]]; then export ZDOTDIR=$_sb_user_zdotdir; else unset ZDOTDIR; fi';

const ZSH_RESTORE = `${ZSH_USER}
unset _sb_init_dir _sb_user_zdotdir _sb_zdotdir_set`;

function zshStep(name) {
  return `${ZSH_USER}
if [[ -f \${ZDOTDIR:-$HOME}/${name} ]]; then builtin source "\${ZDOTDIR:-$HOME}/${name}"; fi
if (( \${+ZDOTDIR} )); then _sb_user_zdotdir=$ZDOTDIR _sb_zdotdir_set=1; else _sb_user_zdotdir= _sb_zdotdir_set=; fi`;
}

const ZSH_FILES = {
  '.zshenv': `${HEADER}typeset -g _sb_init_dir=$ZDOTDIR
if (( \${+SWITCHBOARD_USER_ZDOTDIR} )); then
  typeset -g _sb_user_zdotdir=$SWITCHBOARD_USER_ZDOTDIR _sb_zdotdir_set=1
else
  typeset -g _sb_user_zdotdir= _sb_zdotdir_set=
fi
unset SWITCHBOARD_USER_ZDOTDIR
${zshStep('.zshenv')}
ZDOTDIR=$_sb_init_dir
`,
  '.zprofile': `${HEADER}${zshStep('.zprofile')}
ZDOTDIR=$_sb_init_dir
`,
  '.zshrc': `${HEADER}${zshStep('.zshrc')}
${POSIX_SHIM}
if [[ -o login ]]; then
  ZDOTDIR=$_sb_init_dir
else
${ZSH_RESTORE.replace(/^/gm, '  ')}
fi
`,
  '.zlogin': `${HEADER}${zshStep('.zlogin')}
${ZSH_RESTORE}
`,
};

function shellKind(shellPath, platform) {
  if (isWslShell(shellPath)) return 'posix';
  const base = shellPath.split(/[\\/]/).pop().toLowerCase().replace(/\.exe$/, '');
  if (base.includes('powershell') || base.includes('pwsh') || base === 'cmd' || base === 'nu') return 'none';
  if (base === 'fish') return 'fish';
  if (platform === 'win32') return 'posix';
  if (base.includes('zsh')) return 'zsh';
  if (base.includes('bash')) return 'bash';
  return 'posix';
}

function bashRcPath(initDir) { return path.join(initDir, 'bashrc'); }
function zshDir(initDir) { return path.join(initDir, 'zsh'); }

function writeInitFiles(initDir) {
  fs.mkdirSync(zshDir(initDir), { recursive: true });
  fs.writeFileSync(bashRcPath(initDir), BASHRC);
  for (const [name, content] of Object.entries(ZSH_FILES)) {
    fs.writeFileSync(path.join(zshDir(initDir), name), content);
  }
}

const _written = new Map();
function ensureInitFiles(initDir, log) {
  if (!_written.has(initDir)) {
    try {
      writeInitFiles(initDir);
      _written.set(initDir, true);
    } catch (err) {
      if (log) log.warn(`[plain-terminal] cannot write shell init files in ${initDir}: ${err.message}`);
      _written.set(initDir, false);
    }
  }
  return _written.get(initDir);
}

/**
 * Args, env and the line to type (or null) for a plain terminal's shell.
 * @param {object} o
 * @param {string} o.shell        resolved shell path
 * @param {string[]} o.args       what shellArgs() returns for it
 * @param {object} o.env          the env the shell would otherwise get
 * @param {string|null} o.initDir directory holding the generated files, null if unavailable
 * @param {string} [o.platform]
 */
function plainTerminalLaunch({ shell, args, env, initDir, platform = process.platform }) {
  const kind = shellKind(shell, platform);
  const outEnv = { ...env };
  if (kind === 'bash' && initDir) {
    return { args: ['--rcfile', bashRcPath(initDir), '-i'], env: outEnv, typed: null };
  }
  if (kind === 'zsh' && initDir) {
    delete outEnv.SWITCHBOARD_USER_ZDOTDIR;
    if (env.ZDOTDIR !== undefined) outEnv.SWITCHBOARD_USER_ZDOTDIR = env.ZDOTDIR;
    outEnv.ZDOTDIR = zshDir(initDir);
    return { args, env: outEnv, typed: null };
  }
  if (kind === 'fish') {
    return { args: [...args, '--init-command', FISH_SHIM], env: outEnv, typed: null };
  }
  if (kind === 'none') return { args, env: outEnv, typed: null };
  return { args, env: outEnv, typed: TYPED_SHIM };
}

module.exports = { plainTerminalLaunch, ensureInitFiles, writeInitFiles, TYPED_SHIM, FISH_SHIM, HINT };
